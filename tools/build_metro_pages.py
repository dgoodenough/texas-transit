"""A DFW-style map page for each big metro (study/site_parity.md, phase 2).

    python tools/build_metro_pages.py [ids]     -> docs/metros/<id>.html (+ docs/metros/<id>_layers/)

Each page is DFW Transit's map (vendor/dfw-transit dfwt/webmap.py, through metro/pages.py) on the metro's
generated network (urban/generated/<id>/, named by metro/names.py) and its own model: line and station
pages, the door-to-door trip planner, the data layers and the diagram. Its scenarios are the plan's three
schedules (study/timing.py, docs/data/timeline.json): every line opens in the year that schedule opens it.
"""
import csv
import json
import os
import re
import sys
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VENDOR = os.environ.get("DFW_TRANSIT") or os.path.join(ROOT, "vendor", "dfw-transit")   # another checkout, to test
sys.path.insert(0, os.path.join(ROOT, "study"))
os.environ.setdefault("METRO_HOME", os.path.join(ROOT, "urban"))
os.environ.setdefault("OMP_NUM_THREADS", "2")

BIG = ["houston", "san-antonio", "austin", "el-paso", "rio-grande-valley"]
LABELS = {"ratio": "Best ratio first", "metros_first": "Metros first", "whole_map": "The whole map"}
OUT = os.path.join(ROOT, "docs", "metros")


def schedules(metro_id):
    """{scenario: {line_id: opening year}} from the plan's timeline."""
    T = json.load(open(os.path.join(ROOT, "docs", "data", "timeline.json"), encoding="utf-8"))
    rows = list(csv.DictReader(open(os.path.join(ROOT, "urban", "generated", metro_id, "lines.csv"), encoding="utf-8")))
    by_cand = {}
    for r in rows:
        mm = re.search(r"generated \(([A-Z]+\d+)\)", r.get("notes", ""))
        if mm:
            by_cand[mm.group(1)] = r["line_id"]
    out = {}
    for key in LABELS:
        when = T["scenarios"][key]["when"]
        out[key] = {by_cand[pid.split(":", 1)[1]]: w[1] for pid, w in when.items()
                    if pid.startswith(metro_id + ":") and pid.split(":", 1)[1] in by_cand and w}
    return out


def main(ids):
    import urban_metros
    sys.path = [p for p in sys.path if "dfw-transit" not in p]
    sys.path.insert(0, VENDOR)
    for k in [k for k in sys.modules if k.split(".")[0] in ("metro", "dfwt")]:
        del sys.modules[k]
    from metro import pages
    reg = {m["id"]: m for m in json.load(open(os.path.join(ROOT, "urban", "metros.json"), encoding="utf-8"))["metros"]}
    os.makedirs(OUT, exist_ok=True)
    for mid in ids:
        t0 = time.time()
        m = reg[mid]
        name = m["name"].split(",")[0].split("-")[0]
        if mid == "rio-grande-valley":
            name = "Rio Grande Valley"
        sub = (f"The statewide plan's network for {name}: switch between its three schedules, drag the year, plan a trip "
               "from any address. Generated by DFW Transit's generator; speculative, not an official plan.")
        pages.build(mid, schedules(mid), LABELS, os.path.join(OUT, f"{mid}.html"),
                    policies=urban_metros.policies(m), budget_musd_per_year=m["budget_musd"] / 30,
                    title=f"{name} Transit", sub=sub, back_href="../map.html", back_text="The statewide map")
        print(f"{mid}: {time.time() - t0:.0f}s")


if __name__ == "__main__":
    main(sys.argv[1:] or BIG)
