"""High-speed rail options for Texas: which corridors carry the most riders per dollar, built up
one at a time, in 2050 (trend growth, induced trips).

    python study/hsr_options.py

Greedy: starting from nothing, add the corridor with the most new rail trips (2050, a year) per
$B of its own capital (track and stations not already built), again and again, until every
candidate is in. The order is the ranking; where to stop is a budget question for the statewide
plan (README: about $9B a year in all, for every layer). Writes study/hsr_options.md.
"""
import copy
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from texas import hsr, intercity as ic  # noqa: E402

YEAR = 2050


def evaluate(corridors, tx, zones, p, growth):
    stations = {s: hsr.point(s) for s in hsr.stations_of(corridors)}
    net = ic.RailNetwork(stations, hsr.network_links(corridors, with_speed=True), p["hsr"],
                         services=hsr.services_for(corridors))
    res = ic.run(tx, zones, p, net, growth)
    trips = sum(r["new"]["rail"] + r["new"]["induced"] for r in res.values())
    air = sum(r["base"]["air"] - r["new"]["air"] for r in res.values())
    car = sum(r["base"]["car"] - r["new"]["car"] for r in res.values())
    taken = sum(r["new"]["rail"] for r in res.values())
    assert abs(air + car - taken) < 1e-6 * max(taken, 1), "rail should take exactly what car and air lose"
    return trips, air, car, res


def greedy(tx, zones, p, growth, cost_per_km=None, log=print):
    built, prev, rows = [], 0.0, []
    left = list(hsr.CORRIDORS)
    while left:
        best = None
        for cid in left:
            if any(r not in built for r in hsr.REQUIRES.get(cid, [])):   # a branch waits for its trunk
                continue
            trips = evaluate(built + [cid], tx, zones, p, growth)[0]
            cost = hsr.capital_musd([cid], cost_per_km, built)
            value = (trips - prev) * 365 / 1e6 / (cost / 1000)   # M trips a year per $B
            if best is None or value > best[0]:
                best = (value, cid, trips, cost)
        value, cid, trips, cost = best
        built.append(cid)
        left.remove(cid)
        rows.append((cid, cost, trips - prev, value, trips))
        prev = trips
        if log:
            log(f"  + {cid:6s} ${cost / 1000:5.1f}B  +{(rows[-1][2]) * 365 / 1e6:5.2f}M trips/yr  {value:5.2f}M per $B")
    return rows


def redesign(full, tx, zones, p, growth):
    """The redrawn network against the corridors it replaces (texas/hsr.py REPLACED): everything built."""
    old = [c for c in full if c not in ("BIGC", "WEST", "PANH", "VALLEY", "MFE")] + ["WEST_OLD", "LBB", "RGV"]
    saved = dict(hsr.CORRIDORS)
    hsr.CORRIDORS.update(hsr.REPLACED)
    try:
        t_old = evaluate(old, tx, zones, p, growth)[0]
        c_old = hsr.capital_musd(old)
    finally:
        hsr.CORRIDORS.clear()
        hsr.CORRIDORS.update(saved)
    t_new = evaluate(full, tx, zones, p, growth)[0]
    c_new = hsr.capital_musd(full)
    return ["", "### The redrawn network", "",
            "West Texas branches at Abilene (the Big Country trunk Fort Worth - Weatherford - Abilene, then El Paso and "
            "Lubbock - Amarillo legs) instead of separate Fort Worth - El Paso and Fort Worth - Lubbock lines; the Valley "
            "is reached from Corpus Christi (Kingsville, Harlingen, Brownsville, a McAllen spur) instead of from San "
            "Antonio (`study/cabinet/network.md`). Everything built, same cost model:", "",
            "| Network | Trips a year | Capital |", "|---|---|---|",
            f"| Before (Fort Worth - Lubbock, San Antonio - Valley, no Amarillo) | {t_old * 365 / 1e6:.1f}M | ${c_old / 1000:.0f}B |",
            f"| Redrawn (with Amarillo) | {t_new * 365 / 1e6:.1f}M | ${c_new / 1000:.0f}B |", ""]


def main():
    p = ic.load_params()
    zones = ic.load_zones()
    base = ic.base_trips(zones, p)
    tx = {k: v for k, v in base.items() if "TX" in (zones[k[0]]["state"], zones[k[1]]["state"])}
    growth = ic.zone_growth(zones, YEAR)
    print(f"ranking corridors, {YEAR}:")
    rows = greedy(tx, zones, p, growth)
    out = ["# High-speed rail options for Texas", "",
           f"Generated by `python study/hsr_options.py`. Travel in {YEAR}: today's trips (NextGen NHTS 2022, air from the "
           "airline ticket sample) grown with each zone's population trend (`tools/build_growth.py`: Texas 43M in 2050), "
           f"plus induced trips ({p['hsr']['induced_share']:.0%} of the trips rail takes). Mode choice: `texas/intercity.py`; "
           f"corridors and costs: `texas/hsr.py` ({hsr.SETTINGS['case']} unit costs by context: urban approaches, towns, rugged "
           "and flat rural ground; track along the drawn alignments; stations; 2025 dollars). Branches wait for their "
           "trunks (`texas/hsr.py` REQUIRES). Trains run in service patterns (`texas/hsr.py` PATTERNS: through trains once "
           "their corridors are built, else a shuttle on each corridor); a trip no pattern serves changes trains "
           f"({p['hsr']['transfer_min']} minutes).", "",
           "Corridors are added one at a time, each time the one with the most new rail trips a year per $B of its own "
           "capital. A trip using several corridors counts once. *Built alone* is the corridor with nothing else: "
           "corridors overlap (once Dallas - Austin and Houston - Austin are built, Dallas - Houston trips can already "
           "ride through Austin), so a corridor's value depends on what's built before it.", "",
           "| Order | Corridor | Track km | Capital | New trips a year | Per $B | Built alone: trips a year, per $B | Network trips a year | Network capital |",
           "|---|---|---|---|---|---|---|---|---|"]
    cum = 0.0
    for i, (cid, cost, add, value, total) in enumerate(rows, 1):
        cum += cost
        alone = evaluate([cid], tx, zones, p, growth)[0] * 365 / 1e6
        alone_cost = hsr.capital_musd([cid]) / 1000
        out.append(f"| {i} | {hsr.CORRIDORS[cid][0]} | {hsr.track_km([cid]):,.0f} | ${cost / 1000:.1f}B | "
                   f"{add * 365 / 1e6:.2f}M | {value:.2f}M | {alone:.1f}M, {alone / alone_cost:.2f}M | "
                   f"{total * 365 / 1e6:.1f}M | ${cum / 1000:.0f}B |")
    full = [r[0] for r in rows]
    trips, air, car, res = evaluate(full, tx, zones, p, growth)
    flights = sum(ic.flights_per_day(r["base"]["air"] - r["new"]["air"], p) for r in res.values())
    out += ["", f"**Everything built:** {trips * 365 / 1e6:.1f}M trips a year ({trips:,.0f} a day), "
            f"{car:,.0f} a day from car and {air:,.0f} from air: about {flights:.0f} fewer flights a day.", ""]
    top = sorted(((r["new"]["rail"] + r["new"]["induced"], k) for k, r in res.items()), reverse=True)[:12]
    out += ["Busiest pairs with everything built:", "", "| Pair | Rail trips a day |", "|---|---|"]
    for t, k in top:
        a, b = (ic.short_name(zones[z]) for z in k)
        out.append(f"| {a} - {b} | {t:,.0f} |")
    out += ["", "### Sensitivity (the first four corridors in the ranking; trips a year)", "",
            "| Change | Trips a year | Capital |", "|---|---|---|"]
    first4 = full[:4]
    lo, hi = p["hsr"].get("asc_range", [p["hsr"]["asc_vs_car"]] * 2)
    case0 = hsr.SETTINGS["case"]
    for label, change in (("as above", None), ("low unit costs", ("case", "low")), ("central unit costs", ("case", "central")),
                          ("no induced trips", ("hsr", "induced_share", 0.0)), ("induced 20%", ("hsr", "induced_share", 0.2)),
                          (f"constant {lo:+.2f} (Brightline's low)", ("hsr", "asc_vs_car", lo)),
                          (f"constant {hi:+.2f} (the Northeast's high)", ("hsr", "asc_vs_car", hi)),
                          ("today's travel (no growth)", ("growth",))):
        q, g = copy.deepcopy(p), growth
        if change and change[0] == "case":
            hsr.SETTINGS["case"] = change[1]
        elif change and change[0] == "growth":
            g = None
        elif change:
            q[change[0]][change[1]] = change[2]
        t = evaluate(first4, tx, zones, q, g)[0]
        out.append(f"| {label} | {t * 365 / 1e6:.1f}M | ${hsr.capital_musd(first4) / 1000:.0f}B |")
        hsr.SETTINGS["case"] = case0
    out += redesign(full, tx, zones, p, growth)
    out += ["", "**Caveats.** Rail's constant is calibrated to Brightline and the Northeast Corridor, falling on trips "
            "under 300 km (`study/calibrate_hsr.md`); the other parameters are documented assumptions "
            "(`texas/intercity.json`). Growth is a Census trend extrapolation, "
            "not the Texas Demographic Center's projection. Intercity trips are not comparable one for one with the "
            "urban layer's daily trips (they are longer and worth more to each traveller); comparing the layers needs "
            "user benefits, not trip counts.", "",
            "Operating cost, fares, wider benefits and timing under the budget: `study/timing.md`. Conventional "
            "interstate rail and Monterrey: `study/interstate_rail.md`."]
    text = "\n".join(out) + "\n"
    with open(os.path.join(ROOT, "study", "hsr_options.md"), "w", encoding="utf-8") as f:
        f.write(text)
    print(text)


if __name__ == "__main__":
    main()
