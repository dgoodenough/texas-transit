"""First look at high-speed rail in Texas with today's travel (2022 trips; no growth, no induced
trips): Texas Central as planned, and a Texas Triangle network.

    python study/hsr_first_look.py

Prints the results and writes study/hsr_first_look.md.
"""
import copy
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from texas import intercity as ic  # noqa: E402

STATIONS = {   # approximate sites: downtowns, Texas Central's planned stations
    "Dallas": (32.770, -96.802),           # Texas Central: the Cedars, south of downtown
    "Brazos Valley": (30.590, -96.050),    # Texas Central: Grimes County, for College Station / Huntsville
    "Houston": (29.807, -95.458),          # Texas Central: Northwest Mall, US 290 / I-610
    "Waco": (31.555, -97.130),
    "Temple": (31.098, -97.343),
    "Austin": (30.267, -97.743),
    "San Marcos": (29.883, -97.941),
    "San Antonio": (29.424, -98.493),
}
TRACK = 1.12   # track km per straight-line km between neighbouring stations (assumption)


def links(pairs):
    return [(a, b, ic.km(STATIONS[a], STATIONS[b]) * TRACK) for a, b in pairs]


TEXAS_CENTRAL = [("Dallas", "Brazos Valley"), ("Brazos Valley", "Houston")]
TRIANGLE = TEXAS_CENTRAL + [("Dallas", "Waco"), ("Waco", "Temple"), ("Temple", "Austin"),
                            ("Austin", "San Marcos"), ("San Marcos", "San Antonio"), ("Houston", "San Antonio")]


def summarize(name, res, zones, p):
    rail = sum(r["new"]["rail"] for r in res.values())
    car = sum(r["base"]["car"] - r["new"]["car"] for r in res.values())
    air = sum(r["base"]["air"] - r["new"]["air"] for r in res.values())
    flights = sum(ic.flights_per_day(r["base"]["air"] - r["new"]["air"], p) for r in res.values())
    top = sorted(((r["new"]["rail"], pr, r) for pr, r in res.items() if r["new"]["rail"] > 0), reverse=True)[:8]
    lines = [f"### {name}", "",
             f"- **{rail:,.0f} rail trips a day, {rail * 365 / 1e6:.1f}M a year**: {car:,.0f} from car, {air:,.0f} from air "
             f"({air / max(rail, 1):.0%}); about {flights:.0f} fewer flights a day",
             "", "| Pair | Today (car + air) | Rail | Rail share | From air |", "|---|---|---|---|---|"]
    for t, pr, r in top:
        a, b = (zones[z]["name"].split(",")[0].split("-")[0] for z in pr)
        today = r["base"]["car"] + r["base"]["air"]
        lines.append(f"| {a} - {b} | {today:,.0f} | {t:,.0f} | {t / today:.0%} | {r['base']['air'] - r['new']['air']:,.0f} |")
    return lines, rail


def main():
    p = ic.load_params()
    zones = ic.load_zones()
    base = ic.base_trips(zones, p)
    tx = {k: v for k, v in base.items() if "TX" in (zones[k[0]]["state"], zones[k[1]]["state"])}
    priced = sum(1 for v in tx.values() if v["air_fare"])
    out = ["# High-speed rail in Texas: a first look", "",
           "Generated by `python study/hsr_first_look.py`. Today's travel (NextGen NHTS 2022, air from the airline "
           "ticket sample), every rail line open today, **no growth and no induced trips**: each figure is the share "
           "of today's trips that would switch. Parameters: `texas/intercity.json`.", "",
           f"Base: {len(tx):,} zone pairs at least {p['min_km']} km apart with a Texas end, "
           f"{sum(v['car'] + v['air'] for v in tx.values()):,.0f} trips a day; air from the ticket sample on {priced} of them.", ""]
    dh = next(v for k, v in tx.items() if {zones[k[0]]["name"][:6], zones[k[1]]["name"][:6]} == {"Dallas", "Housto"})
    out += [f"Dallas - Houston today: {dh['car'] + dh['air']:,.0f} trips a day, {dh['air'] / (dh['car'] + dh['air']):.0%} by air, "
            f"{dh['work_share']:.0%} for work.", ""]
    results = {}
    for name, net_links in (("Texas Central (Dallas - Brazos Valley - Houston)", TEXAS_CENTRAL),
                            ("Texas Triangle (Texas Central + Dallas - Austin - San Antonio + Houston - San Antonio)", TRIANGLE)):
        net = ic.RailNetwork(STATIONS, links(net_links), p["hsr"])
        lines, rail = summarize(name, ic.run(tx, zones, p, net), zones, p)
        results[name] = rail
        out += lines + [""]
    out += ["### Sensitivity (Texas Central, rail trips a day)", "", "| Change | Rail trips a day | A year |", "|---|---|---|"]
    for label, path, value in (("as above", None, None), ("constant vs car 0 (no penalty)", ("hsr", "asc_vs_car"), 0.0),
                               ("constant vs car -1.0", ("hsr", "asc_vs_car"), -1.0),
                               ("fare 30% lower", ("hsr", "fare_per_km"), p["hsr"]["fare_per_km"] * 0.7),
                               ("trains every 60 min", ("hsr", "headway_min"), 60),
                               ("air-rail nest 0.4 (closer substitutes)", ("nest_public_scale",), 0.4),
                               ("no nest (plain logit)", ("nest_public_scale",), 1.0)):
        q = copy.deepcopy(p)
        if path and len(path) == 2:
            q[path[0]][path[1]] = value
        elif path:
            q[path[0]] = value
        net = ic.RailNetwork(STATIONS, links(TEXAS_CENTRAL), q["hsr"])
        rail = sum(r["new"]["rail"] for r in ic.run(tx, zones, q, net).values())
        out.append(f"| {label} | {rail:,.0f} | {rail * 365 / 1e6:.1f}M |")
    out += ["", "Benchmarks for Dallas - Houston: TxDOT (2013) 0.7-2.7M riders a year by 2035; Reason Foundation (2017) "
            "1.4M by 2035; Texas Central 5-6M a year early on and 10-13M by 2050 (with growth and induced trips)."]
    text = "\n".join(out) + "\n"
    with open(os.path.join(ROOT, "study", "hsr_first_look.md"), "w", encoding="utf-8") as f:
        f.write(text)
    print(text)


if __name__ == "__main__":
    main()
