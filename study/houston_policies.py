"""Why Houston's transit share fell when the 2 million plan's policies were switched on
(study/metro_potential.md), on a fixed network.

    python study/houston_policies.py

Takes the default generated Houston network from the model test (urban/potential/houston_network/,
DFW's 75-year spending, no policies) and runs DFW Transit's demand model on it, today's land use:
  - with no policies, then each policy alone, then all of them, the ridership constant held at the
    value fitted on today's network with today's policies (+0.836, NTD's 43,920 weekday riders);
  - all policies with the constant refitted under them, which is what the generator did: Houston is
    the one metro whose constant is fitted on every run (registry `calibration`), and it was fitted
    with the policies switched on.
Austin (fixed constant from the registry) runs the same way as a control.

Writes study/houston_policies.md.
"""
import copy
import csv
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.environ["METRO_HOME"] = os.path.join(ROOT, "urban")
os.environ.setdefault("OMP_NUM_THREADS", "2")
sys.path.insert(0, os.path.join(ROOT, "vendor", "dfw-transit"))
sys.path.insert(0, os.path.join(ROOT, "study"))
from dfwt import config, evaluate  # noqa: E402
from metro import centers, generate, inputs, model, output  # noqa: E402
import metro_potential as mp  # noqa: E402

L = mp.LEVERS
VARIANTS = [
    ("no policies", {}),
    ("feeder buses every 15 min", {"access": {"feeder": L["access"]["feeder"]}}),
    ("bikes and scooters to stations", {"access": {"micromobility": L["access"]["micromobility"]}}),
    ("drop-off", {"access": {"kiss_ride": L["access"]["kiss_ride"]}}),
    ("1.6 km walks, straighter streets", {"access": {"walk_max_m": 1600, "walk_circuity": 1.15}}),
    ("no park & ride under 1.6 km", {"access": {"pnr_min_km": 1.6}}),
    ("parking prices", {"ridership": L["ridership"]}),
    ("all policies", L),
]


def read_tables(folder):
    out = {}
    for name in list(inputs.TABLES) + list(output.OPTIONAL_EMPTY):
        p = os.path.join(folder, name)
        out[name] = inputs.read_csv(p) if os.path.exists(p) else []
    return out


def run(mid, folder):
    m = inputs.load(mid)
    gp = generate.params(mid)
    cp = gp["centers"]
    urban = centers.find(m, centers.Surface(m, cp["grid_km"], cp["kernel_km"]), cp)
    centers.classify(m, urban, cp)
    tables = read_tables(folder)
    base_cfg = config.load()
    entry = generate.registry_entry(mid, m)
    rows = []
    fixed_asc = None
    for label, lev, refit in [(lab, lev, False) for lab, lev in VARIANTS] + [("all policies, constant refitted under them", L, True)]:
        cfg0 = copy.deepcopy(base_cfg)
        config.merge(cfg0, copy.deepcopy(lev))
        cfg = model.metro_cfg(m, urban, cfg0)
        ex = generate.Existing(m, cfg["modes"])
        ctx, _ = model.gravity_od(m, cfg)
        if fixed_asc is None:   # today's policies: the constant as the plan uses it
            generate.ridership_constant(mid, m, cfg, ctx, ex, log=lambda s: None)
            fixed_asc = cfg["ridership"]["asc"]
        elif refit and entry.get("calibration"):
            generate.ridership_constant(mid, m, cfg, ctx, ex, log=lambda s: None)
        else:
            cfg["ridership"]["asc"] = fixed_asc
        res = output.model_runs(m, cfg, ctx, tables, ex)
        g, e = res["generated"], res["existing"] or {}
        commutes = float(cfg["demand"]["total_commutes"]) * cfg["ridership"]["telework"]
        rows.append({"variant": label, "asc": cfg["ridership"]["asc"], "share": g["transit_commuters"] / commutes,
                     "trips": g["daily_trips"], "today_trips": e.get("daily_trips", 0.0),
                     "today_boardings": e.get("daily_boardings", 0.0)})
        print(f"  {mid} {label}: asc {cfg['ridership']['asc']:+.3f}, {rows[-1]['share']:.2%}, {g['daily_trips']:,.0f} trips; "
              f"today's lines {rows[-1]['today_boardings']:,.0f} boardings")
    return rows


def main():
    res = {mid: run(mid, os.path.join(ROOT, "urban", "potential", f"{mid}_network")) for mid in ("houston", "austin")}
    L_ = ["# Houston and the policies", "",
          "Generated by `python study/houston_policies.py`. The model test (`study/metro_potential.md`) found Houston's "
          "transit share falling when the 2 million plan's policies were switched on. Here the network is held fixed (the "
          "default generated network at DFW's 75-year spending) and DFW Transit's demand model runs on it with each policy "
          "alone, then all of them, on today's land use. Austin is the control.", ""]
    for mid, rows in res.items():
        base = rows[0]["share"]
        L_ += [f"## {mid.replace('-', ' ').title()}", "",
               "| Policies | Ridership constant | Transit share of commutes | Change | Daily trips | Today's lines: weekday boardings |",
               "|---|---|---|---|---|---|"]
        for r in rows:
            L_.append(f"| {r['variant']} | {r['asc']:+.3f} | {r['share']:.2%} | {r['share'] / base - 1:+.0%} | "
                      f"{r['trips']:,.0f} | {r['today_boardings']:,.0f} |")
        L_.append("")
    with open(os.path.join(ROOT, "study", "houston_policies.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(L_))
    json.dump(res, open(os.path.join(ROOT, "study", "houston_policies.json"), "w"), indent=1)
    print("\n".join(L_))


if __name__ == "__main__":
    main()
