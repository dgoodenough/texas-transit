"""The plan's record (study/hsr_buildout.md, Phase 5): where the plan stands, every number from a run.

    python study/plan_record.py

Reads docs/data/timeline.json (written by `python study/timing.py`), the Auditor's decade review
(study/decade_review.py) and the generated metro networks (urban/generated/, measured as
study/router.py does), and rewrites the "Where the plan stands" section of study/hsr_buildout.md
between its markers. The cabinet session and the Phase 1 and 2 results below it stay as written: the
record of how the plan got here, with the numbers of their day. Run it after any model change.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "study"))
import decade_review  # noqa: E402
import router  # noqa: E402

DOC = os.path.join(ROOT, "study", "hsr_buildout.md")
START = "<!-- plan-record: generated by `python study/plan_record.py`; edits here are overwritten -->"
END = "<!-- /plan-record -->"
SCEN = ("ratio", "metros_first", "whole_map")
STD = {"S1": "320 km/h double track", "S2": "250 km/h double track", "S3": "250 km/h single track, passing loops",
       "S4": "200 km/h single track first"}
LEVER_TEXT = {"costs": "a delivery office that learns (against costs as built today)", "rail_fund": "the Rail Fund",
              "surplus": "the Triangle's surplus pledged", "federal": "the 10% federal match",
              "partners": "the neighbouring states paying for the track in theirs (with the federal money granted to them)"}
BIG = ("houston", "san-antonio", "austin", "el-paso")


def money(m):
    return f"${m / 1000:,.1f}B" if abs(m) >= 1000 else f"${m:,.0f}M"


def label(name):
    return name.split(":")[0] if ":" in name else name.split(" - ")[-1]


def key(T, on, costs=None):
    return "|".join((costs or ("central" if on else "high")) if k == "costs" else ("1" if on else "0") for k in T["lever_names"])


def flip(T, base_on, lever):
    """The grid key with every lever at base_on except `lever`, which is the other way."""
    out = []
    for k in T["lever_names"]:
        on = base_on != (k == lever)
        out.append(("central" if on else "high") if k == "costs" else ("1" if on else "0"))
    return "|".join(out)


def record(T):
    WP = {p["id"]: p for p in T["whole_map_projects"]}
    P = {p["id"]: p for p in T["projects"]}
    conn = T["connectivity"]
    hsr_ids = sorted(p["id"] for p in T["projects"] if p["layer"] == "hsr")
    L = [START, "", "## Where the plan stands", "",
         "*Generated by `python study/plan_record.py` from `docs/data/timeline.json` (`python study/timing.py`), the "
         "Auditor's decade review (`python study/decade_review.py`, `study/decade_review.md`) and the generated metro "
         "networks (`urban/generated/`, measured as `study/router.py` does). Every number here comes from those runs; "
         "the cabinet session and the Phase 1 and 2 results further down are the record of how the plan got here, with "
         "the numbers of their day.*", ""]

    off, on = T["levers"][key(T, False)], T["levers"][key(T, True)]
    yrs = [on["opens"][i] for i in conn if on["opens"].get(i)]
    dm = on["metro_2100"] - off["metro_2100"]
    L += [f"**The answer.** Built as Texas builds today, with no money of their own, {off['branches']} of {len(conn)} branch "
          f"corridors open by 2100. With a delivery office that learns, an eighth of a cent of sales tax (the Rail Fund), "
          f"the Triangle's operating surplus, a 10% federal match and the neighbouring states paying for the track in theirs, "
          + (f"all {len(conn)} open by {max(yrs)}" if on["branches"] == len(conn) else f"{on['branches']} of {len(conn)} open by 2100")
          + f", for {money(on['branches_texas'])} of Texas's money, and the metros "
          + (f"give up nothing: {dm:,.0f} more new daily trips in 2100 than without the levers, because the branches no "
             "longer draw on the statewide budget." if dm > 0 else
             "give up nothing: every metro line is built by 2100 either way." if dm == 0 else
             f"carry {-dm:,.0f} fewer new daily trips in 2100.")
          + " (`timeline.json` levers, the whole-map schedule for each setting.)", ""]

    def row(lab, f):
        return f"| {lab} | " + " | ".join(f(k) for k in SCEN) + " |"

    def last_year(k, field):
        Y = T["scenarios"][k]["yearly"]
        return Y[-1][field]

    def year(k, y, field):
        return next(r[field] for r in T["scenarios"][k]["yearly"] if r["year"] == y)

    def opened(k, ids):
        w = T["scenarios"][k]["when"]
        return [i for i in ids if i in w]

    def hsr_km(k):
        src = WP if k == "whole_map" else P
        return sum(src[i]["km"] for i in opened(k, hsr_ids) if i in src)

    def last_branch(k):
        w, o = T["scenarios"][k]["when"], opened(k, conn)
        return str(max(w[i][1] for i in o)) if len(o) == len(conn) else "not all by 2100"

    L += ["### The three schedules", "",
          "| | " + " | ".join(T["scenarios"][k]["label"] for k in SCEN) + " |", "|---|---|---|---|",
          row("High-speed corridors open by 2100", lambda k: f"{len(opened(k, hsr_ids))} of {len(hsr_ids)}"),
          row("High-speed km open by 2100", lambda k: f"{hsr_km(k):,.0f}"),
          row("Branch corridors open by 2100", lambda k: f"{len(opened(k, conn))} of {len(conn)}"),
          row("The last branch opens", last_branch),
          row("Intercity rail trips a year, 2100", lambda k: f"{last_year(k, 'intercity_trips_year') / 1e6:,.0f}M"),
          row("New daily metro trips, 2100 (DFW included)",
              lambda k: f"{last_year(k, 'urban_trips_day') + last_year(k, 'dfw_trips_day'):,.0f}"),
          row("Capital spent 2025-2100 (DFW included)",
              lambda k: money(sum(r["spend"] + r["dfw_spend"] for r in T["scenarios"][k]["yearly"]))),
          row("Net benefit a year, 2100 (travellers, wider, fares less opex)", lambda k: money(last_year(k, "net"))),
          row("Operating cost less fares a year, 2050 / 2100", lambda k: money(year(k, 2050, "opex") - year(k, 2050, "fares"))
              + " / " + money(last_year(k, "opex") - last_year(k, "fares"))),
          row("Operating cost less fares, 2025-2100 (no budget pays it yet)",
              lambda k: money(sum(r["opex"] - r["fares"] for r in T["scenarios"][k]["yearly"]))),
          "", f"Budget: {money(T['budget_musd'])} a year statewide ({money(T['dfw_musd'])} of it DFW's own plan), 2025-2100. "
          "High-speed km for the whole map are its redrawn, lighter-standard corridors; for the other two, today's cost model.", ""]

    L += ["### The branches", "",
          "| Corridor | Standard | Capital | Texas pays | Ratio (P10-P90) | Under stress | " + " | ".join(
              T["scenarios"][k]["label"] for k in SCEN) + " |", "|---|---|---|---|---|---|---|---|---|"]
    for i in sorted(conn, key=lambda i: (T["scenarios"]["whole_map"]["when"].get(i) or [0, 9999])[1]):
        p = WP[i]
        cells = [(T["scenarios"][k]["when"].get(i) or [None, "not by 2100"])[1] for k in SCEN]
        L.append(f"| {label(p['name'])} ({p['name'].split(': ')[-1]}) | {STD.get(p.get('standard'), '')} | {money(p['capital'])} | "
                 f"{money(p['capital'] - p.get('outside', 0))} | {p['bcr']:.2f} ({p['bcr_p10']:.2f}-{p['bcr_p90']:.2f}) | "
                 f"{p['bcr_stress']:.2f} | " + " | ".join(map(str, cells)) + " |")
    L += ["", "Capital and ratios are the whole map's (its cost model, standards and opening years); Texas pays the capital less "
          "the federal match and the partner states' share.", ""]

    L += ["### What each lever is worth", "",
          "From every lever on, switching one off; and from none, switching one on (the whole-map schedule rerun each time):", "",
          "| Lever | All on but this: branches open | last opens | Texas's high-speed capital | None but this: branches open | last opens |",
          "|---|---|---|---|---|---|"]
    for lv in T["lever_names"]:
        a, b = T["levers"][flip(T, True, lv)], T["levers"][flip(T, False, lv)]

        def last(r):
            ys = [r["opens"][i] for i in conn if r["opens"].get(i)]
            return str(max(ys)) if len(ys) == len(conn) else "not all by 2100"
        L.append(f"| {LEVER_TEXT.get(lv, lv)} | {a['branches']} of {len(conn)} | {last(a)} | {money(a['hsr_texas'])} | "
                 f"{b['branches']} of {len(conn)} | {last(b)} |")
    L += ["", f"Every lever on: {on['branches']} of {len(conn)}, the last in {max(yrs) if yrs else 'none'}, "
          f"{money(on['hsr_texas'])} of high-speed capital from Texas. None: {off['branches']} of {len(conn)}, "
          f"{money(off['hsr_texas'])}.", ""]

    rows = decade_review.review(T, "whole_map")
    holds = [r for r in rows if r["gate2"] == "hold"]
    desig = [r for r in rows if r["gate3"] == "designated"]
    fail = [r for r in rows if r["gate3"] == "fail"]
    passed = [r for r in rows if r["gate3"] == "pass"]
    L += ["### The Auditor's review", "",
          f"Of {len(rows)} intercity projects in the whole map, {len(holds)} start before their trunk has run "
          f"{decade_review.GATE_YEARS} years (the schedule now applies that gate itself); {len(passed)} clear the stress gate "
          f"(a ratio of {decade_review.STRESS_MIN} at cost x1.45 and riders x0.70); {len(desig)} proceed on the Connectivity "
          f"Program's designation; {len(fail)} fail it without one. So the plan is a policy choice made on the central case "
          "and its range, to be re-made each decade at current costs and riders (`study/decade_review.md`), not a sure "
          "investment.", ""]

    reg = {m["id"]: m for m in json.load(open(os.path.join(ROOT, "urban", "metros.json"), encoding="utf-8"))["metros"]}
    L += ["### The metros' networks (Phase 3)", "",
          "| Metro | New lines | Metro lines through downtown | Anchors served | Daily trips | Capital |", "|---|---|---|---|---|---|"]
    for mid in BIG:
        r = router.measure(os.path.join(ROOT, "urban", "generated", mid), reg[mid].get("anchors") or [])
        if not r:
            continue
        L.append(f"| {reg[mid]['name'].split(',')[0].split('-')[0]} | {r['lines']} | {r.get('through', 0)} of {r.get('metro', 0)} | "
                 f"{sum(ok for _, ok in r['anchors'])} of {len(r['anchors'])} | {r['trips']:,.0f} | {money(r['capital'])} |")
    L += ["", "From the generated networks (`urban/generated/`); `study/router.md` compares them with the networks before "
          "the Phase 3 changes and says what isn't done.", "", END]
    return "\n".join(L)


def main():
    T = json.load(open(os.path.join(ROOT, "docs", "data", "timeline.json"), encoding="utf-8"))
    text = open(DOC, encoding="utf-8").read()
    rec = record(T)
    if START in text and END in text:
        a, b = text.index(START), text.index(END) + len(END)
        text = text[:a] + rec + text[b:]
    else:   # first run: after the opening note, before "## The question"
        i = text.index("## The question")
        text = text[:i] + rec + "\n\n" + text[i:]
    with open(DOC, "w", encoding="utf-8") as f:
        f.write(text)
    print(rec)


if __name__ == "__main__":
    main()
